use std::sync::Arc;

use anyhow::Result;
use teloxide::prelude::*;

mod admin;
mod bot;
mod config;
mod db;
mod logger;
mod models;

use config::Config;

/// Общий контекст приложения.
///
/// В дальнейшем сюда будут добавляться:
///
/// • Redis
/// • кэш
/// • SMTP
/// • внешние API
/// • сервис статистики
///
/// Благодаря этому обработчики не будут хранить множество отдельных
/// зависимостей.
#[derive(Clone)]
pub struct AppState {
    /// Конфигурация приложения.
    pub config: Arc<Config>,

    /// Пул соединений с PostgreSQL.
    pub db: sqlx::PgPool,
}

#[tokio::main]
async fn main() -> Result<()> {
    //
    // ---------------------------------------------------------------------
    // Инициализация логирования
    // ---------------------------------------------------------------------
    //
    logger::init();

    log::info!("===========================================");
    log::info!(" Запуск Telegram-бота недвижимости");
    log::info!("===========================================");

    //
    // ---------------------------------------------------------------------
    // Загружаем конфигурацию
    // ---------------------------------------------------------------------
    //
    let config = Arc::new(Config::from_env()?);

    log::info!("Конфигурация успешно загружена.");

    //
    // ---------------------------------------------------------------------
    // Подключаемся к PostgreSQL
    // ---------------------------------------------------------------------
    //
    let db_pool = db::connect(&config.database_url).await?;

    log::info!("Подключение к PostgreSQL выполнено.");

    //
    // ---------------------------------------------------------------------
    // Применяем миграции
    // ---------------------------------------------------------------------
    //
    // Папка migrations будет создана позже.
    //
    db::migrate(&db_pool).await?;

    log::info!("Миграции успешно применены.");

    //
    // ---------------------------------------------------------------------
    // Создаем состояние приложения
    // ---------------------------------------------------------------------
    //
    let state = AppState {
        config: config.clone(),
        db: db_pool,
    };

    //
    // ---------------------------------------------------------------------
    // Создаем Telegram Bot
    // ---------------------------------------------------------------------
    //
    let bot = Bot::new(config.telegram_token.clone());

    log::info!("Telegram Bot успешно создан.");

    //
    // ---------------------------------------------------------------------
    // Запускаем Dispatcher
    // ---------------------------------------------------------------------
    //
    bot::run(bot, state).await?;

    Ok(())
}